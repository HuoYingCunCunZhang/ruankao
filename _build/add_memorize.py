"""为指定章节的各小节插入 memorize（记忆技巧）字段。"""
import re, json, os, sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

build_dir = os.path.dirname(os.path.abspath(__file__))

def add(chapter_file, mem_map):
    path = os.path.join(build_dir, chapter_file)
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    out = []
    current = None
    inserted = 0
    for line in lines:
        m = re.search(r'num: "(11\.\d+)"', line) if 'id: "s11.' in line else None
        if m:
            current = m.group(1)
        if line.strip().startswith('body: ') and current in mem_map:
            indent = line[:len(line)-len(line.lstrip())]
            out.append(indent + 'memorize: ' + json.dumps(mem_map[current], ensure_ascii=False) + ',')
            inserted += 1
            current = None
        out.append(line)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print(f"{chapter_file}: 插入 {inserted} 处 memorize")

